async function main() {
  console.log(`[seed-tactical-profiles] Starting — ${PROFILES.length} profiles to seed`);

  // Check already-seeded countries
  const { data: existing } = await supabase
    .from("team_tactical_profiles")
    .select("country");
  const seededCountries = new Set((existing ?? []).map((r: { country: string }) => r.country));
  const toInsert = PROFILES.filter((p) => !seededCountries.has(p.country));

  if (toInsert.length === 0) {
    console.log("[seed-tactical-profiles] All profiles already seeded. Done.");
    return;
  }
  console.log(`[seed-tactical-profiles] Inserting ${toInsert.length} profiles (${seededCountries.size} already exist)`);

  const { error } = await supabase
    .from("team_tactical_profiles")
    .insert(toInsert);

  if (error) {
    console.error("[seed-tactical-profiles] Insert error:", error.message);
    process.exit(1);
  }

  console.log(`[seed-tactical-profiles] Done — ${toInsert.length} profiles inserted`);
}

main().catch((e) => { console.error(e); process.exit(1); });
